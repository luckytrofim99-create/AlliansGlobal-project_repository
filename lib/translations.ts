export function translate(locale: "ru" | "en", text: string) {
  if (locale === "ru") return text;
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const key = text.trim();
  return `${leading}${englishCopy[key] ?? key}${trailing}`;
}
